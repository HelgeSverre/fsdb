#!/usr/bin/env python3
"""Generate MySQL 8.4's BMP Boolean-query word classifier from Unicode 5.0.

Usage: generate-boolean-word-chars.py UnicodeData.txt [output.fs]
The input is https://www.unicode.org/Public/5.0.0/ucd/UnicodeData.txt.
MySQL's source names the draft UnicodeData-5.0.0d9.txt; the final file has
21 additional ideographs (U+9FA6..U+9FBA), excluded below.
"""

from hashlib import sha256
from pathlib import Path
import sys


EXPECTED_SHA256 = "e458a6cab52182af09cb40defab6d00e6927d51ef7291017647e9c10b3e196b9"
OUTPUT = Path(__file__).resolve().parents[2] / "src/Fsdb/Sql/BooleanWordChars.fs"


def codepoints(path: Path) -> set[int]:
    data = path.read_bytes()
    actual = sha256(data).hexdigest()
    if actual != EXPECTED_SHA256:
        raise SystemExit(f"unexpected UnicodeData.txt SHA-256: {actual}")

    result: set[int] = set()
    first: tuple[int, str] | None = None
    for line in data.decode("utf-8").splitlines():
        fields = line.split(";")
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp, category
        elif name.endswith(", Last>"):
            if first and category[0] in "LNM":
                result.update(range(first[0], min(cp, 0xFFFF) + 1))
            first = None
        elif cp <= 0xFFFF and category[0] in "LNM":
            result.add(cp)
    result.difference_update(range(0x9FA6, 0x9FBB))
    if len(result) != 48108:
        raise SystemExit(f"unexpected MySQL-compatible word-character count: {len(result)}")
    return result


def ranges(points: set[int]) -> list[tuple[int, int]]:
    output: list[tuple[int, int]] = []
    for cp in sorted(points):
        if output and cp == output[-1][1] + 1:
            output[-1] = output[-1][0], cp
        else:
            output.append((cp, cp))
    return output


def main() -> None:
    path = Path(sys.argv[1])
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else OUTPUT
    pairs = ranges(codepoints(path))
    lines = [
        "// Generated by torture/scripts/generate-boolean-word-chars.py from Unicode 5.0.0.",
        "// MySQL 8.4 uses draft UnicodeData-5.0.0d9 for its BMP ctype table.",
        "// The final Unicode file's 21 additional U+9FA6..U+9FBA characters are excluded.",
        "module internal Fsdb.BooleanWordChars",
        "",
        "let private ranges: (int * int)[] =",
        "    [|",
        *("        " + "; ".join(
            f"0x{lo:04X}, 0x{hi:04X}" for lo, hi in pairs[i : i + 4]
        ) + ";" for i in range(0, len(pairs), 4)),
        "    |]",
        "",
        "/// MySQL's historical Boolean-query word boundary, plus its underscore rule.",
        "let contains (c: char) =",
        "    if c = '_' then true",
        "    else",
        "        let value = int c",
        "        let mutable low = 0",
        "        let mutable high = ranges.Length - 1",
        "        let mutable found = false",
        "        while low <= high && not found do",
        "            let middle = low + (high - low) / 2",
        "            let first, last = ranges.[middle]",
        "            if value < first then high <- middle - 1",
        "            elif value > last then low <- middle + 1",
        "            else found <- true",
        "        found",
        "",
    ]
    output.write_text("\n".join(lines))
    print(f"wrote {len(pairs)} ranges to {output}")


if __name__ == "__main__":
    main()
